<?php

use App\Http\Controllers\AdminController;
use App\Http\Controllers\AuthController;
use App\Http\Controllers\CatalogController;
use App\Http\Controllers\ChatController;
use App\Http\Controllers\IngredientController;
use App\Http\Controllers\OrderController;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Route;

Route::post('auth/refresh', [AuthController::class, 'refresh'])->middleware('throttle:30,1');
Route::post('auth/register', [AuthController::class, 'register'])->middleware('throttle:10,1');
Route::post('auth/login', [AuthController::class, 'login'])->middleware('throttle:10,1');
Route::post('auth/forgot-password', [AuthController::class, 'forgot'])->middleware('throttle:3,1');
Route::post('auth/reset-password', [AuthController::class, 'reset'])->middleware('throttle:5,1');
Route::get('categories', [CatalogController::class, 'categories']);
Route::get('products', [CatalogController::class, 'products']);
Route::get('products/{product}', [CatalogController::class, 'product'])->whereNumber('product');
Route::get('toppings', [CatalogController::class, 'toppings']);
Route::post('chat', [ChatController::class, 'chat'])->middleware('throttle:chat');
Route::post('chat/stream', [ChatController::class, 'stream'])->middleware('throttle:chat');
Route::get('chat/conversations/{uuid}', [ChatController::class, 'show'])->whereUuid('uuid')->middleware('throttle:60,1');
Route::middleware(['auth:sanctum', 'active'])->group(function () {
    Route::get('auth/me', fn (Request $r) => $r->user());
    Route::post('auth/logout', [AuthController::class, 'logout']);
    Route::patch('profile', [AuthController::class, 'profile']);
    Route::put('profile/password', [AuthController::class, 'password']);
    Route::match(['get', 'put'], 'cart', [AuthController::class, 'cart']);
    Route::get('chat/conversations', [ChatController::class, 'conversations']);
    Route::get('orders', [OrderController::class, 'index']);
    Route::post('orders', [OrderController::class, 'store']);
    Route::get('orders/{order}', [OrderController::class, 'show']);
    Route::post('orders/{order}/mock-payment', [OrderController::class, 'pay']);
    Route::post('products/{product}/reviews', [CatalogController::class, 'review']);
    Route::post('vouchers/check', [CatalogController::class, 'voucher'])->middleware('throttle:20,1');
    Route::prefix('admin')->middleware('admin')->group(function () {
        Route::get('statistics', [AdminController::class, 'statistics']);
        Route::get('reports', [AdminController::class, 'export']);
        Route::get('orders', [AdminController::class, 'orders']);
        Route::patch('orders/{order}/status', [OrderController::class, 'status']);
        Route::get('customers', [AdminController::class, 'customers']);
        Route::get('customers/{user}', [AdminController::class, 'customer']);
        Route::patch('customers/{user}', [AdminController::class, 'block']);
        Route::get('ingredients', [IngredientController::class, 'index']);
        Route::post('ingredients', [IngredientController::class, 'save']);
        Route::put('ingredients/{ingredient}', [IngredientController::class, 'save']);
        Route::delete('ingredients/{ingredient}', [IngredientController::class, 'destroy']);
        Route::get('ingredient-imports', [IngredientController::class, 'imports']);
        Route::post('ingredient-imports', [IngredientController::class, 'storeImport']);
        Route::get('reviews', [AdminController::class, 'reviews']);
        Route::patch('reviews/{review}', [AdminController::class, 'moderate']);
        Route::delete('reviews/{review}', [AdminController::class, 'deleteReview']);
        Route::get('products', [AdminController::class, 'products']);
        Route::post('products', [AdminController::class, 'saveProduct']);
        Route::put('products/{product}', [AdminController::class, 'saveProduct']);
        Route::delete('products/{product}', [AdminController::class, 'deleteProduct']);
        Route::post('categories', [AdminController::class, 'saveCategory']);
        Route::put('categories/{category}', [AdminController::class, 'saveCategory']);
        Route::delete('categories/{category}', [AdminController::class, 'deleteCategory']);
        Route::post('uploads', [AdminController::class, 'upload']);
        Route::get('toppings', [AdminController::class, 'toppings']);
        Route::post('toppings', [AdminController::class, 'saveTopping']);
        Route::put('toppings/{topping}', [AdminController::class, 'saveTopping']);
        Route::delete('toppings/{topping}', [AdminController::class, 'deleteTopping']);
        Route::get('vouchers', [AdminController::class, 'vouchers']);
        Route::post('vouchers', [AdminController::class, 'saveVoucher']);
        Route::put('vouchers/{voucher}', [AdminController::class, 'saveVoucher']);
        Route::delete('vouchers/{voucher}', [AdminController::class, 'deleteVoucher']);
    });
});
